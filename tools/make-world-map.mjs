// Builds src/components/worldMapData.js: one SVG path per country, already projected, so the
// app needs no map library at runtime. Run once (the output is committed); only re-run to
// change the map's look.
//
//   mkdir /tmp/mapgen && cd /tmp/mapgen && npm init -y
//   npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1 i18n-iso-countries@7.14.0
//   node /path/to/watchnext/tools/make-world-map.mjs /tmp/mapgen /path/to/watchnext/src/components/worldMapData.js
//
// Data: Natural Earth 1:110m via world-atlas (public domain). Tiny countries (Hong Kong,
// Singapore…) aren't drawn at this scale; the app still lists them under the map.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const [modDir, outFile] = process.argv.slice(2);
if (!modDir || !outFile) {
  console.error('usage: node make-world-map.mjs <dir with node_modules> <output .js>');
  process.exit(1);
}
const req = createRequire(path.join(path.resolve(modDir), 'package.json'));
const { feature } = req('topojson-client');
const { geoPath, geoEqualEarth } = await import(req.resolve('d3-geo'));
const countries = req('i18n-iso-countries');
const topo = JSON.parse(fs.readFileSync(req.resolve('world-atlas/countries-110m.json'), 'utf8'));

const W = 1000;
const H = 480;
const fc = feature(topo, topo.objects.countries);
fc.features = fc.features.filter((f) => f.properties.name !== 'Antarctica');
const projection = geoEqualEarth().fitExtent([[4, 4], [W - 4, H - 4]], fc);

// Round to 1 decimal to keep the file small.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
const BY_NAME = { Kosovo: 'XK', 'N. Cyprus': 'CY', Somaliland: 'SO' }; // features world-atlas leaves without a code

const out = [];
for (const f of fc.features) {
  const code = (f.id && countries.numericToAlpha2(f.id)) || BY_NAME[f.properties.name] || null;
  const d = geoPath(projection)(f);
  if (!d) continue;
  out.push([code || '', round(d)]);
}
// A country split over several features (Cyprus + N. Cyprus) becomes one path.
const merged = new Map();
for (const [code, d] of out) {
  const k = code || '?' + merged.size;
  merged.set(k, (merged.get(k) || '') + d);
}
const rows = [...merged].map(([k, d]) => `  [${JSON.stringify(k.startsWith('?') ? '' : k)}, ${JSON.stringify(d)}],`);
const src = `// GENERATED by tools/make-world-map.mjs from Natural Earth 1:110m (public domain). Do not edit.
// [ISO 3166-1 alpha-2 code ('' = no code), SVG path] in a ${W}x${H} Equal Earth view.
export const VIEW_W = ${W};
export const VIEW_H = ${H};
export const COUNTRY_PATHS = [
${rows.join('\n')}
];
`;
fs.writeFileSync(outFile, src);
console.log(`${merged.size} shapes, ${(src.length / 1024).toFixed(0)} KB -> ${outFile}`);
